--
-- Source: minna_no_nihongo_kanji_list.csv. jlpt_level, on_yomi, kun_yomi,
-- kan_viet, and meaning_vi all came pre-filled in that file (no
-- cross-referencing or new data needed, unlike the いろどり kanji list).
--
-- Stroke-order animation on the card back reuses the app's existing
-- StrokeOrderAnimation (HanziWriter) component.

create table if not exists public.minna_kanji_db (
  id bigint generated always as identity primary key,
  kanji text not null,
  on_yomi text not null,
  kun_yomi text not null,
  jlpt_level text not null check (jlpt_level in ('N5', 'N4')),
  unit int not null,
  kan_viet text not null,
  meaning_vi text not null,
  sort_order int not null
);

alter table public.minna_kanji_db enable row level security;

drop policy if exists "public read" on public.minna_kanji_db;
create policy "public read"
  on public.minna_kanji_db
  for select
  to anon, authenticated
  using (true);

