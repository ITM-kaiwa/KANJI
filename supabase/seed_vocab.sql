-- Run this once in Supabase Studio (SQL Editor) for the KANJI project
-- (https://ltxqagtohxzjfrztbbdq.supabase.co).
--
-- Creates the `vocab_db` table (read-only from the browser) and seeds it
-- with "Minna no Nihongo" Bai 1-50 vocabulary (Bai 1-25 = N5, 26-50 = N4),
-- sourced from the sister ITM project (Synth's `vocab_cards` table) with
-- placeholder/duplicate rows removed (1,620 clean rows: 878 N5 + 742 N4).
--
-- Also extends review_state's content_type check constraint to allow
-- 'vocab', since vocab flashcards use the same anonymous-device SRS as
-- kanji/kana.

create table if not exists public.vocab_db (
  id bigint generated always as identity primary key,
  jlpt_level text not null check (jlpt_level in ('N5', 'N4')),
  lesson int not null,
  word text not null,
  reading text not null,
  romaji text not null default '',
  meaning_vi text not null,
  sort_order int not null
);

alter table public.vocab_db enable row level security;

drop policy if exists "public read" on public.vocab_db;
create policy "public read"
  on public.vocab_db
  for select
  to anon, authenticated
  using (true);

-- Idempotent: safe to re-run without creating duplicate rows.
delete from public.vocab_db;

alter table public.review_state drop constraint if exists review_state_content_type_check;
alter table public.review_state
  add constraint review_state_content_type_check
  check (content_type in ('kanji', 'hiragana', 'katakana', 'vocab'));

