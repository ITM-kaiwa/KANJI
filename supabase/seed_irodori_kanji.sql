-- translations of the Japanese reading) -- worth spot-checking since it's
-- a first pass, unlike the 479 reused from the verified kanji_db source.
--
-- Stroke-order animation on the card back reuses the app's existing
-- StrokeOrderAnimation (HanziWriter) component, which isn't limited to
-- kanji_db -- it works for any of these 644 characters directly.

create table if not exists public.irodori_kanji_db (
  id bigint generated always as identity primary key,
  kanji text not null,
  reading text not null,
  example_word text not null,
  example_reading text not null,
  book_label text not null check (
    book_label in ('いろどり入門', 'いろどり初級1', 'いろどり初級2', 'いろどり初中級')
  ),
  lesson int not null,
  kan_viet text not null,
  meaning_vi text not null,
  sort_order int not null
);

alter table public.irodori_kanji_db enable row level security;

drop policy if exists "public read" on public.irodori_kanji_db;
create policy "public read"
  on public.irodori_kanji_db
  for select
  to anon, authenticated
  using (true);

