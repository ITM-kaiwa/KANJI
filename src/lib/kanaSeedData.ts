function buildEntries(kanaType: KanaType): KanaEntry[] {
  const charIndex: 0 | 1 = kanaType === "hiragana" ? 0 : 1;
  return ROWS.map(([hiragana, katakana, romaji, group], i) => ({
    id: (kanaType === "hiragana" ? 1000 : 2000) + i,
    character: [hiragana, katakana][charIndex],
    kanaType,
    romaji,
    groupName: group,
  }));
}

export const KANA_SEED_DATA: KanaEntry[] = [
  ...buildEntries("hiragana"),
  ...buildEntries("katakana"),
];
